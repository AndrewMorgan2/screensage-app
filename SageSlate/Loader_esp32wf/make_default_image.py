"""
Bakes SageSlate/bg_images/sage_slate_<N>.png into default_image.h, which the
firmware displays at boot (see showDefaultImage() in Loader_esp32wf.ino).

Run this whenever srvr.h's hostname number changes, then re-flash.
"""
import argparse
import re
import sys
from pathlib import Path

import numpy as np
from PIL import Image

SCRIPT_DIR = Path(__file__).resolve().parent
IMAGE_DIR = SCRIPT_DIR.parent / "bg_images"
SRVR_H = SCRIPT_DIR / "srvr.h"
OUTPUT_H = SCRIPT_DIR / "default_image.h"

WIDTH, HEIGHT = 400, 300


def detect_screen_number():
    match = re.search(r'hostname\s*=\s*"[^"]*?(\d+)"', SRVR_H.read_text())
    if not match:
        sys.exit("Could not auto-detect screen number from srvr.h; pass --number explicitly.")
    return int(match.group(1))


def load_image(number):
    path = IMAGE_DIR / f"sage_slate_{number}.png"
    if not path.exists():
        sys.exit(f"No background image found for screen #{number}: {path}")
    return Image.open(path).convert("RGB").resize((WIDTH, HEIGHT))


def pack_bits(image):
    # Same convention as your_image.py: white pixel -> bit 1, black -> bit 0.
    data = np.array(image.convert("1"))
    bits = data.flatten() > 0
    packed = bytearray((len(bits) + 7) // 8)
    for i, bit in enumerate(bits):
        if bit:
            packed[i // 8] |= 1 << (7 - (i % 8))
    return packed


def write_header(packed, number):
    lines = [
        "// Auto-generated by make_default_image.py -- do not edit by hand.",
        "#pragma once",
        "#include <Arduino.h>",
        "",
        f"#define DEFAULT_IMAGE_SCREEN_NUMBER {number}",
        "",
        f"const uint8_t default_image[{len(packed)}] PROGMEM = {{",
    ]
    for i in range(0, len(packed), 16):
        chunk = packed[i:i + 16]
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in chunk) + ",")
    lines.append("};")
    OUTPUT_H.write_text("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--number", type=int, help="Screen number to use (default: read from srvr.h hostname)")
    args = parser.parse_args()

    number = args.number if args.number is not None else detect_screen_number()
    print(f"Baking default image for screen #{number} from {IMAGE_DIR}/sage_slate_{number}.png...")

    packed = pack_bits(load_image(number))
    write_header(packed, number)
    print(f"Wrote {OUTPUT_H} ({len(packed)} bytes)")


if __name__ == "__main__":
    main()
